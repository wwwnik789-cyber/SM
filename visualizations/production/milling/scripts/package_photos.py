#!/usr/bin/env python3
"""Export/check the seven curated milling JPEGs: WebP, alt CSV, overview, ZIPs.

The JPEGs are the curated deliverables, not generated by this packaging script.
No network access, image-generation API or Tilda publication is performed here.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import zipfile

from PIL import Image, ImageCms, ImageDraw, ImageFont

FOLDER = Path(__file__).resolve().parents[1]
MANIFEST = FOLDER / 'manifest.json'
OVERVIEW = 'sm-production-milling-overview.jpg'
ARCHIVES = {'jpeg': 'sm-production-milling-jpeg.zip', 'webp': 'sm-production-milling-webp.zip'}
FONTDIR = Path('/usr/share/fonts/truetype/dejavu')
# Reuse the curated sRGB profile rather than inserting a fresh profile creation
# timestamp on each rebuild. The same input JPEGs produce byte-stable exports.
with Image.open(FOLDER / 'sm-production-milling-01-workshop.jpg') as reference:
    ICC = reference.info['icc_profile']


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def file_info(path: Path) -> dict:
    return {'file': path.name, 'bytes': path.stat().st_size, 'sha256': digest(path)}


def font(size: int, bold: bool = False):
    return ImageFont.truetype(str(FONTDIR / ('DejaVuSans-Bold.ttf' if bold else 'DejaVuSans.ttf')), size)


def overview(data):
    width = 1920
    margin, gap = 48, 24
    col = (width - 2 * margin - 2 * gap) // 3
    photo_h = col * 2 // 3
    row_h = photo_h + 65
    top = 144
    height = top + 3 * row_h + 70
    canvas = Image.new('RGB', (width, height), '#f3f5f6')
    draw = ImageDraw.Draw(canvas)
    navy = '#203247'
    draw.text((margin, 30), 'SM PRODUCTION  /  ФРЕЗЕРОВКА', fill=navy, font=font(33, True))
    draw.text((margin, 82), 'Серия для сайта · 7 фотографий · единый горизонтальный формат 3:2', fill='#64717c', font=font(23))
    for i, item in enumerate(data['images']):
        x = margin + i % 3 * (col + gap)
        y = top + i // 3 * row_h
        with Image.open(FOLDER / (item['basename'] + '.jpg')) as im:
            thumb = im.resize((col, photo_h), Image.Resampling.LANCZOS)
        canvas.paste(thumb, (x, y))
        draw.text((x, y + photo_h + 11), f"{item['number']:02}  {item['title']}", fill=navy, font=font(20, True))
    x = margin + col + gap
    y = top + 2 * row_h
    right = width - margin
    draw.rounded_rectangle((x, y, right, y + photo_h), radius=12, fill='#e5ebef')
    tx, ty = x + 34, y + 30
    draw.text((tx, ty), 'Готово к ручной загрузке на сайт', fill=navy, font=font(28, True))
    lines = [
        'JPEG: 1680 × 1120 px · sRGB',
        'WebP: 1260 × 840 px · облегчённые копии',
        'Названия файлов и alt — в комплекте',
        '01, 06–07: без генеративной перерисовки',
        'В 02–05 расширены края с применением ИИ',
    ]
    for i, line in enumerate(lines):
        draw.text((tx, ty + 65 + i * 47), line, fill='#506171', font=font(23))
    draw.text((margin, height - 58), 'Обзор для выбора кадров. На сайт загружать отдельные изображения, не этот лист.', fill='#64717c', font=font(21))
    canvas.save(FOLDER / OVERVIEW, quality=92, subsampling=0, optimize=True, progressive=True, icc_profile=ICC)


def archive(name, paths):
    with zipfile.ZipFile(FOLDER / name, 'w', compression=zipfile.ZIP_STORED) as z:
        for path in paths:
            # Fixed ZIP metadata makes repackaging reproducible; no source EXIF/GPS is copied.
            entry = zipfile.ZipInfo(path.name, date_time=(1980, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_STORED
            entry.external_attr = 0o644 << 16
            z.writestr(entry, path.read_bytes())


def build():
    data = json.loads(MANIFEST.read_text())
    assert len(data['images']) == 7
    for item in data['images']:
        jpg = FOLDER / (item['basename'] + '.jpg')
        with Image.open(jpg) as source:
            assert source.size == (1680, 1120) and source.mode == 'RGB'
            im = source.resize((1260, 840), Image.Resampling.LANCZOS)
        webp = FOLDER / (item['basename'] + '.webp')
        im.save(webp, quality=84, method=6, icc_profile=ICC)
        item['exports'] = {'jpeg': file_info(jpg), 'webp': file_info(webp)}
    with (FOLDER / 'image-alt.csv').open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f, delimiter=';', lineterminator='\n')
        writer.writerow(['Номер', 'Исходник', 'JPEG', 'WebP', 'Alt'])
        for item in data['images']:
            writer.writerow([item['number'], item['source']['filename'], item['basename'] + '.jpg', item['basename'] + '.webp', item['alt']])
    overview(data)
    for kind, name in ARCHIVES.items():
        archive(name, [FOLDER / item['exports'][kind]['file'] for item in data['images']])
    data['overview'] = file_info(FOLDER / OVERVIEW)
    data['archives'] = {kind: file_info(FOLDER / name) for kind, name in ARCHIVES.items()}
    data['alt_register'] = file_info(FOLDER / 'image-alt.csv')
    data['totals'] = {kind: sum(item['exports'][kind]['bytes'] for item in data['images']) for kind in ARCHIVES}
    MANIFEST.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    check(data)


def check(data=None):
    if data is None:
        data = json.loads(MANIFEST.read_text())
    assert len(data['images']) == 7
    assert [i['number'] for i in data['images']] == list(range(1, 8))
    assert len({i['source']['filename'] for i in data['images']}) == 7
    expected = {'IMG_2993.jpg', 'IMG_7308.jpg', 'DSC_1249.JPG', 'IMG_0481.jpg', 'IMG_1667 копия.jpg', 'IMG_1706.jpg', 'IMG_1707.jpg'}
    assert {i['source']['filename'] for i in data['images']} == expected
    for item in data['images']:
        assert item['alt'].strip() and '[' not in item['alt']
        assert len(item['source']['sha256']) == 64
        for kind, size in [('jpeg', (1680, 1120)), ('webp', (1260, 840))]:
            info = item['exports'][kind]
            path = FOLDER / info['file']
            assert file_info(path) == info
            with Image.open(path) as im:
                im.load()
                assert im.size == size and im.mode == 'RGB'
                assert im.width * 2 == im.height * 3
                assert not im.getexif(), f'Unexpected EXIF in {path.name}'
                profile = im.info.get('icc_profile')
                assert profile, f'Missing sRGB profile: {path.name}'
                description = ImageCms.getProfileDescription(ImageCms.ImageCmsProfile(io.BytesIO(profile)))
                assert description.strip().lower().startswith('srgb'), f'Not sRGB: {path.name}'
                assert im.format == ('JPEG' if kind == 'jpeg' else 'WEBP')
            assert path.stat().st_size < (1_500_000 if kind == 'jpeg' else 600_000)
    with (FOLDER / 'image-alt.csv').open(encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f, delimiter=';'))
    assert len(rows) == 7
    for row, item in zip(rows, data['images']):
        assert row['Alt'] == item['alt'] and row['Исходник'] == item['source']['filename']
        assert row['JPEG'] == item['exports']['jpeg']['file']
        assert row['WebP'] == item['exports']['webp']['file']
    for kind, info in data['archives'].items():
        path = FOLDER / info['file']
        assert file_info(path) == info
        expected_files = {i['exports'][kind]['file'] for i in data['images']}
        with zipfile.ZipFile(path) as z:
            assert z.testzip() is None
            assert len(z.namelist()) == 7 and set(z.namelist()) == expected_files
            for name in z.namelist():
                assert z.read(name) == (FOLDER / name).read_bytes()
    for key in ['overview', 'alt_register']:
        info = data[key]
        assert file_info(FOLDER / info['file']) == info
    assert len(list(FOLDER.glob('sm-production-milling-[0-9][0-9]-*.jpg'))) == 7
    assert len(list(FOLDER.glob('sm-production-milling-[0-9][0-9]-*.webp'))) == 7
    print('PASS: 7 JPEG + 7 WebP, 3:2, sRGB, no EXIF/GPS, file-weight limits, 7 alt texts, SHA-256 and two exact 7-file ZIPs.')
    print(f"JPEG total: {data['totals']['jpeg']:,} bytes; WebP total: {data['totals']['webp']:,} bytes")
    for kind, info in data['archives'].items():
        print(f"{kind}: {info['file']} ({info['bytes']:,} bytes), SHA256 {info['sha256']}")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check current deliverables without rewriting them')
    args = parser.parse_args()
    check() if args.check else build()
