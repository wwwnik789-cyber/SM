#!/usr/bin/env python3
"""Собирает PDF «Страница «Контакты» по блокам».

Берёт разбивку из bloki.json (её делает split_blocks.py) и раскладывает по
страницам: карта блоков, потом каждый блок с пояснением и кодом.

    .venv/bin/python docs/kontakty-pravka/build_blocks_pdf.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "marketing"))
sys.path.insert(0, str(HERE))

from pdfkit import MUTED, NAVY, Doc, register_fonts  # noqa: E402
from build_pdf import Pdf, register_mono  # noqa: E402

OUT = HERE / "stranica-po-blokam.pdf"
INDEX = HERE / "bloki.json"
BLOCK_DIR = HERE / "bloki"


def main() -> int:
    register_fonts()
    register_mono()

    blocks = json.loads(INDEX.read_text(encoding="utf-8"))
    data_blocks = [b for b in blocks if b["num"] <= 7]
    page_blocks = [b for b in blocks if b["num"] >= 8]

    d = Pdf(
        OUT,
        kicker="Страница «Контакты» по блокам",
        title="Страница контактов по блокам: что за что отвечает",
        subtitle="18 частей вместо одного файла на 356 строк. Текст на экране почти всегда "
                 "правится в семи блоках данных — до разметки дело не доходит.",
        meta=[
            ("Файл", "src/pages/Contacts.jsx"),
            ("Блоков", "18: 7 с данными и 11 с разметкой"),
            ("Куски файла", "docs/kontakty-pravka/bloki/"),
            ("Строк", "356, номера в PDF — настоящие, как в редакторе"),
        ],
        note="Разбивка сделана скриптом: блоки склеиваются обратно в исходный файл байт в байт "
             "(20 049 символов). Ничего не добавлено и не удалено — поэтому блок можно менять отдельно.",
        footer="SM-Production · страница «Контакты» по блокам · внутренний документ",
    )

    # ── как пользоваться ──────────────────────────────────────────────────
    d.h1("Как этим пользоваться")
    d.p("Страница собрана как конструктор: сверху вниз идут куски, из которых складывается файл. "
        "Править можно один кусок, не переписывая всю страницу целиком.")
    d.bullet("Номера строк в PDF — настоящие номера файла. В редакторе нажмите Ctrl+G и введите "
             "номер, чтобы попасть в нужное место.")
    d.bullet("Данные (блоки 01–07) лежат в начале файла — это адреса, цифры, тексты карточек. "
             "Разметка (блоки 08–18) — ниже, она рисует блоки на экране.")
    d.bullet("Чаще всего менять нужно блоки 02–07: там текст. Разметку трогают, только если "
             "нужен другой вид блока, а не другое содержание.")
    d.bullet("Заменить один блок: найдите в файле его первую и последнюю строку по номерам, "
             "выделите этот кусок и вставьте новый из папки bloki.")
    d.callout("Одна лишняя скобка в разметке — и сайт не соберётся. Поэтому текст правьте в блоках "
              "данных: там ошибка почти невозможна, а на экране меняется всё сразу.")

    # ── карта блоков ──────────────────────────────────────────────────────
    d.h1("Карта блоков")
    d.h2("Данные и настройки")
    d.table(
        [["№", "Блок", "Строки", "Что это"]] +
        [[f"{b['num']:02d}", b["title"].split(":")[0], f"{b['start']}–{b['end']}", b["screen"].split(".")[0]]
         for b in data_blocks],
        widths=[0.28, 1.16, 0.42, 1.75], size=8.4,
    )
    d.h2("Компонент и блоки страницы")
    d.table(
        [["№", "Блок", "Строки", "Что видно на экране"]] +
        [[f"{b['num']:02d}", b["title"].split(":")[0], f"{b['start']}–{b['end']}", b["screen"].split(".")[0]]
         for b in page_blocks],
        widths=[0.28, 1.16, 0.42, 1.75], size=8.4,
    )

    # ── часть 1 ───────────────────────────────────────────────────────────
    d.new_page()
    d.h1("Часть 1. Данные и настройки")
    d.p("Семь блоков в начале файла. Здесь нет внешнего вида — только значения: адрес, часы, "
        "ссылки, тексты карточек и вопросы. Меняется текст — меняется страница.")
    for b in data_blocks:
        d.need(150)
        d.h2(f"{b['num']:02d} · {b['title']}")
        d.p(f"Строки {b['start']}–{b['end']} · файл {b['slug']}.jsx", size=9.6, color=MUTED)
        d.p(b["screen"], size=10.2)
        d.p(b["edit"], size=10.2)
        text = (BLOCK_DIR / f"{b['slug']}.jsx").read_text(encoding="utf-8").rstrip("\n")
        d.code(text, size=7.4, numbered=True, offset=b["start"] - 1)

    # ── часть 2 ───────────────────────────────────────────────────────────
    d.new_page()
    d.h1("Часть 2. Компонент и блоки страницы")
    d.p("Одиннадцать блоков, из которых складывается сама страница. Идут в том же порядке, "
        "в каком видны на экране, если листать сверху вниз.")
    for b in page_blocks:
        d.need(170)
        d.h2(f"{b['num']:02d} · {b['title']}")
        d.p(f"Строки {b['start']}–{b['end']} · файл {b['slug']}.jsx", size=9.6, color=MUTED)
        d.p(b["screen"], size=10.2)
        d.p(b["edit"], size=10.2)
        text = (BLOCK_DIR / f"{b['slug']}.jsx").read_text(encoding="utf-8").rstrip("\n")
        d.code(text, size=7.2, numbered=True, offset=b["start"] - 1)

    # ── если сломалось ────────────────────────────────────────────────────
    d.new_page()
    d.h1("Если что-то сломалось")
    d.bullet("Белая страница или красная ошибка в браузере — откройте терминал: там будет номер "
             "строки, на которую ругается сборка. Ctrl+Z в редакторе отменяет последнюю правку.")
    d.bullet("Вернуть один блок проще, чем весь файл: скопируйте нужный кусок из папки bloki "
             "и замените им испорченный, сохранив номера строк.")
    d.bullet("Перед публикацией запустите npm run build. Команда прошла без ошибок — страница соберётся.")
    d.bullet("Если правили много и потерялись — скачайте файл заново с GitHub и начните с блока, "
             "на котором остановились.")
    d.gap(6)
    d.callout("Проверить, что блоки не разъехались: запустите split_blocks.py — скрипт склеит куски "
              "и сравнит с исходным файлом. Совпало — значит, ничего не потеряно.")

    d.save()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
