def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)

    OUT_DIR.mkdir(exist_ok=True)
    for old in OUT_DIR.glob("*.jsx"):
        old.unlink()

    starts: list[int] = []
    for num, slug, title, anchor, screen, edit in BLOCKS:
        if anchor is None:                     # первый блок: с начала файла
            starts.append(1)
            continue
        hit = [i + 1 for i, line in enumerate(lines) if anchor in line]
        if len(hit) != 1:
            print(f"  ✗ якорь «{anchor}» найден {len(hit)} раз, нужен ровно один")
            return 1
        starts.append(hit[0])

    made = []
    for idx, (num, slug, title, anchor, screen, edit) in enumerate(BLOCKS):
        start = starts[idx]
        end = starts[idx + 1] - 1 if idx + 1 < len(starts) else len(lines)
        chunk = "".join(lines[start - 1:end])
        (OUT_DIR / f"{slug}.jsx").write_text(chunk, encoding="utf-8")
        made.append({
            "num": num, "slug": slug, "title": title,
            "start": start, "end": end,
            "lines": end - start + 1,
            "chars": len(chunk),
            "screen": screen, "edit": edit,
        })

    # главная проверка: склейка по порядку = исходный файл, байт в байт
    glue = "".join((OUT_DIR / f"{b['slug']}.jsx").read_text(encoding="utf-8") for b in made)
    if glue != text:
        print("  ✗ блоки не совпадают с исходником")
        return 1
    if made[-1]["end"] != len(lines):
        print(f"  ✗ последний блок кончается на {made[-1]['end']}, а в файле {len(lines)} строк")
        return 1

    INDEX.write_text(json.dumps(made, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"  ✓ {len(made)} блоков в {OUT_DIR.relative_to(ROOT)}/")
    print(f"  ✓ склейка совпала с src/pages/Contacts.jsx: {len(text):,} символов".replace(",", " "))
    for b in made:
        print(f"    {b['num']:02d} {b['slug']:<20} {b['start']:>3}–{b['end']:<3} {b['lines']:>3} строк")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
