def thumb(path, w_px=520):
    if path in THUMBS:
        return THUMBS[path]
    from PIL import Image
    out = '/tmp/thumb_%d.jpg' % abs(hash(path))
    im = Image.open(path).convert('RGB')
    k = w_px / im.size[0]
    im = im.resize((w_px, max(1, int(im.size[1] * k))), Image.LANCZOS)
    im.save(out, 'JPEG', quality=86, optimize=True)
    THUMBS[path] = out
    return out


