def w_(s, font, size):
    return pdfmetrics.stringWidth(s, font, size)


def wrap(s, font, size, width_mm):
    words, line, out = s.split(), '', []
    for word in words:
        t = (line + ' ' + word).strip()
        if w_(t, font, size) <= width_mm * mm:
            line = t
        else:
            if line:
                out.append(line)
            line = word
    if line:
        out.append(line)
    return out or ['']


class Doc:
    def __init__(self, path):
        self.c = canvas.Canvas(path, pagesize=A4)
        self.page = 0
        self.y = TOP
        self.shown = True

    # --- примитивы
    def t(self, x, y, s, font='R', size=8.3, color=INK, anchor='l'):
        c = self.c
        c.setFont(font, size)
        c.setFillColor(color)
        yy = H - y * mm
        if anchor == 'l':
            c.drawString(x * mm, yy, s)
        elif anchor == 'r':
            c.drawRightString(x * mm, yy, s)
        else:
            c.drawCentredString(x * mm, yy, s)

    def para(self, x, y, s, font='R', size=8.3, lead=1.42, color=INK,
             width=CW, anchor='l'):
        lines = wrap(s, font, size, width)
        step = size * lead
        for i, ln in enumerate(lines):
            self.t(x, y + i * step / mm, ln, font, size, color, anchor)
        return len(lines) * step / mm

    def rule(self, x1, y, x2, color=LINE, w=0.5):
        c = self.c
        c.setStrokeColor(color)
        c.setLineWidth(w)
        c.line(x1 * mm, H - y * mm, x2 * mm, H - y * mm)

    def box(self, x, y, w, h, fill=CARD, stroke=None, r=1.4):
        c = self.c
        c.setLineWidth(0.5)
        if fill:
            c.setFillColor(fill)
        if stroke:
            c.setStrokeColor(stroke)
        c.roundRect(x * mm, H - (y + h) * mm, w * mm, h * mm, r * mm,
                    stroke=1 if stroke else 0, fill=1 if fill else 0)

    def chip(self, x, y, label, size=6.4, fg=OR, bg=None, border=None, pad=2.2, h=5.2):
        tw = w_(label, 'SB', size) / mm
        w = tw + pad * 2
        if bg:
            self.box(x, y, w, h, fill=bg, stroke=border, r=h / 2)
        self.t(x + pad, y + h * 0.68, label, 'SB', size, fg)
        return w

    # --- страницы
    def new_page(self, section=''):
        self.flush()
        self.page += 1
        self.c.setFillColor(PAPER)
        self.c.rect(0, 0, W, H, fill=1, stroke=0)
        self.t(ML, 13, 'SM-PRODUCTION · СТРАНИЦА ДЛЯ TILDA · БРЕНДИНГ АВТОСАЛОНОВ',
               'SB', 6.2, DIM)
        if section:
            self.t(210 - MR, 13, section, 'SB', 6.2, DIM, 'r')
        self.rule(ML, 15.5, 210 - MR)
        self.t(ML, 288, 'файл: SM-Tilda-Avtosalony-verstka.pdf', 'R', 6, DIM)
        self.t(210 - MR, 288, '%02d' % self.page, 'B', 6.5, MUT, 'r')
        self.y = TOP
        self.shown = False

    def flush(self):
        if self.page and not self.shown:
            self.c.showPage()
            self.shown = True

    def save(self):
        self.flush()
        self.c.save()


