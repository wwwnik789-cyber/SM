def load() -> list[dict[str, str]]:
    rows = list(csv.DictReader((HERE / "platforms.csv").open(encoding="utf-8")))
    return [r for r in rows if r["tier"] != "X"]


def by_tier(rows, tier):
    return sorted([r for r in rows if r["tier"] == tier],
                  key=lambda r: (r["priority"], r["name"]))


def counts(rows):
    free = sum(1 for r in rows if "Бесплат" in r["cost"] or "есплат" in r["cost"])
    return len(rows), free, len(by_tier(rows, "A"))


