def register_fonts() -> None:
    need = {"Montserrat": "Regular", "Montserrat-Med": "Medium",
            "Montserrat-Semi": "SemiBold", "Montserrat-Bold": "Bold"}
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    for name, weight in [("Regular", 400), ("Medium", 500),
                         ("SemiBold", 600), ("Bold", 700)]:
        out = FONT_DIR / f"Montserrat-{name}.ttf"
        # пересобираем, если файла нет или он остался вариативным (крупнее 500 КБ)
        if out.exists() and out.stat().st_size < 500_000:
            continue
        from fontTools.ttLib import TTFont as FTFont
        from fontTools.varLib.instancer import instantiateVariableFont
        ft = FTFont(str(FONT_SRC))
        # ВАЖНО: instancer возвращает новый объект — сохранять надо его
        static = instantiateVariableFont(ft, {"wght": weight}, updateFontNames=True)
        static.save(str(out))
    for alias, suffix in need.items():
        pdfmetrics.registerFont(TTFont(alias, str(FONT_DIR / f"Montserrat-{suffix}.ttf")))
    pdfmetrics.registerFontFamily("Montserrat", normal="Montserrat",
                                  bold="Montserrat-Bold", italic="Montserrat",
                                  boldItalic="Montserrat-Bold")


register_fonts()

