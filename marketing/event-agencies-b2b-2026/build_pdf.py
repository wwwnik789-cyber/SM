class Rule(Flowable):
    def __init__(self, width, thickness=0.6, color=LINE, space=0):
        super().__init__()
        self.width, self.thickness, self.color, self.space = width, thickness, color, space
        self.height = thickness + space

    def draw(self):
        self.canv.setStrokeColor(self.color)
        self.canv.setLineWidth(self.thickness)
        self.canv.line(0, self.height - self.thickness, self.width, self.height - self.thickness)


class SectionHead(Flowable):
    """Номер раздела крупно + название, с полосой акцента."""
    def __init__(self, number, title, subtitle="", width=CONTENT_W):
        super().__init__()
        self.number, self.title, self.subtitle = number, title, subtitle
        self.width = width
        self.height = 26 if not subtitle else 34

    def draw(self):
        c = self.canv
        c.setFillColor(ORANGE)
        c.rect(0, self.height - 3, 26, 3, stroke=0, fill=1)
        c.setFont("Montserrat-Bold", 20)
        c.setFillColor(ORANGE)
        c.drawString(0, self.height - 24, self.number)
        num_w = c.stringWidth(self.number, "Montserrat-Bold", 20)
        x = num_w + 7
        c.setFont("Montserrat-Bold", 16)
        c.setFillColor(INK)
        c.drawString(x, self.height - 24, self.title)
        if self.subtitle:
            c.setFont("Montserrat", 8.4)
            c.setFillColor(MUTED)
            c.drawString(x, self.height - 35, self.subtitle)


class Callout(Flowable):
    """Плашка с цитатой/оффером: полоса слева + текст."""
    def __init__(self, text, width=CONTENT_W, fill=CREAM, bar=ORANGE,
                 pad=9, fs=9.6):
        super().__init__()
        self.width = width
        self.fill, self.bar, self.pad = fill, bar, pad
        rgb = fill.red + fill.green + fill.blue
        fg = WHITE if rgb < 1.4 else colors.HexColor("#2A2A35")
        self.para = Paragraph(text, S("call", fontName="Montserrat-Med", fontSize=fs,
                                      leading=fs * 1.45, textColor=fg))
        self.pw = width - pad * 2 - 3
        _, self.ph = self.para.wrap(self.pw, 500)
        self.height = self.ph + pad * 2

    def draw(self):
        c = self.canv
        c.setFillColor(self.fill)
        c.rect(0, 0, self.width, self.height, stroke=0, fill=1)
        c.setFillColor(self.bar)
        c.rect(0, 0, 3, self.height, stroke=0, fill=1)
        self.para.drawOn(c, self.pad + 3, self.pad)


class KPI(Flowable):
    """Ряд крупных цифр: [(значение, подпись), ...]."""
    def __init__(self, items, width=CONTENT_W, dark=False):
        super().__init__()
        self.items, self.width, self.dark = items, width, dark
        self.height = 46

    def draw(self):
        c = self.canv
        n = len(self.items)
        col = self.width / n
        for i, (value, label) in enumerate(self.items):
            x = i * col
            if i:
                c.setStrokeColor(LINE)
                c.setLineWidth(0.5)
                c.line(x, 6, x, self.height - 4)
            c.setFillColor(WHITE if self.dark else INK)
            fs = 19.0
            avail = col - 16
            while fs > 11 and c.stringWidth(value, "Montserrat-Bold", fs) > avail:
                fs -= 0.5
            c.setFont("Montserrat-Bold", fs)
            c.drawString(x + 8, self.height - 24, value)
            c.setFillColor(colors.HexColor("#9C9CA6") if self.dark else MUTED)
            c.setFont("Montserrat", 7.6)
            for j, chunk in enumerate(_wrap(label, int(col / 4.0))):
                c.drawString(x + 8, self.height - 36 - j * 9, chunk)


def _wrap(text, width_chars):
    words, lines, cur = text.split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 <= width_chars:
            cur = (cur + " " + w).strip()
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines[:2]


def bullets(items, style=st_bullet):
    return [Paragraph(f"•&nbsp;&nbsp;{t}", style) for t in items]


def table(data, widths, head=True, fs=8.0, align=None, zebra=True):
    rows = []
    for r_i, row in enumerate(data):
        cells = []
        for cell in row:
            if isinstance(cell, str):
                style = st_cell_head if (head and r_i == 0) else st_cell
                cells.append(Paragraph(cell, style))
            else:
                cells.append(cell)
        rows.append(cells)
    t = Table(rows, colWidths=widths, repeatRows=1 if head else 0)
    cmds = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 3.6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3.6),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
    ]
    if head:
        cmds += [("BACKGROUND", (0, 0), (-1, 0), INK),
                 ("TOPPADDING", (0, 0), (-1, 0), 5),
                 ("BOTTOMPADDING", (0, 0), (-1, 0), 5)]
    if zebra:
        for i in range(1 if head else 0, len(rows)):
            if (i - (1 if head else 0)) % 2 == 1:
                cmds.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor("#FAF9F6")))
    t.setStyle(TableStyle(cmds))
    return t


